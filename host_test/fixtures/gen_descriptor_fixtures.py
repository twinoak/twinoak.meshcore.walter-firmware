#!/usr/bin/env python3
"""Turn spec/fixtures/manifest/index.json's `descriptors` into a C++ table for the host tests.

    python3 gen_descriptor_fixtures.py <index.json> <out.h>

host_test/CMakeLists.txt runs this at build time, so the table is index.json's and never a
transcription of it: an entry added to the fixtures becomes a case the tests run, and a field
changed there changes what they expect. The alternative - a JSON reader inside the tests - would
be a parser of our own to get right before it could prove anything about the descriptor.

Standard library only. The output is deterministic: the same index.json gives the same bytes.
"""

import json
import sys

HEADER = """// Generated by host_test/fixtures/gen_descriptor_fixtures.py from
// spec/fixtures/manifest/index.json. Do not edit; it is rewritten by every build.
//
// `descriptors` of the fixture index, as a table the tests walk: for each stand-in image, whether
// spec/FIRMWARE-MANIFEST.md section 4 says it holds exactly one valid descriptor, at what offset,
// which 96 bytes, and what they mean. The image files themselves are read from
// TWINOAK_SPEC_FIXTURES at run time.
#pragma once

#include <cstddef>
#include <cstdint>

namespace fixtures {

struct Descriptor {
  const char* image;       // the file name, under TWINOAK_SPEC_FIXTURES
  bool valid;              // index.json's `valid`: exactly one parseable descriptor in the image
  const char* why;         // index.json's `why`, when it is not valid; nullptr when it is
  std::size_t offset;      // where the one descriptor is, when valid
  const char* hex;         // its 96 bytes, when valid
  std::uint8_t role;       // the fields index.json records for it, when valid
  const char* role_name;
  std::uint8_t slot;
  std::uint8_t link_major;
  std::uint8_t link_minor;
  std::uint16_t flags;
  const char* version;
  const char* board;
  const char* band;
};

"""

ROLES = {"unknown": 0, "repeater": 1, "bridge": 2, "scanner": 3, "manager": 16}


def c_string(value):
    if value is None:
        return "nullptr"
    out = []
    for ch in value:
        if ch in ('"', "\\"):
            out.append("\\" + ch)
        elif " " <= ch <= "~":
            out.append(ch)
        else:
            raise ValueError("fixture string %r is not printable ASCII" % value)
    return '"' + "".join(out) + '"'


def main(argv):
    if len(argv) != 3:
        print(__doc__)
        return 2
    with open(argv[1], "r", encoding="utf-8") as fh:
        index = json.load(fh)

    rows = []
    for entry in index["descriptors"]:
        fields = entry.get("fields", {})
        role_name = fields.get("role")
        if role_name is not None and role_name not in ROLES:
            raise ValueError("index.json names role %r, which section 4 does not" % role_name)
        rows.append(
            "    {%s, %s, %s, %s, %s,\n     %d, %s, %d, %d, %d, %d, %s, %s, %s},"
            % (
                c_string(entry["image"]),
                "true" if entry["valid"] else "false",
                c_string(entry.get("why")),
                "0x%X" % entry.get("offset", 0),
                c_string(entry.get("hex")),
                ROLES.get(role_name, 0),
                c_string(role_name),
                fields.get("slot", 0),
                fields.get("link_major", 0),
                fields.get("link_minor", 0),
                fields.get("flags", 0),
                c_string(fields.get("version")),
                c_string(fields.get("board")),
                c_string(fields.get("band")),
            )
        )

    text = HEADER
    text += "inline constexpr Descriptor kDescriptors[] = {\n%s\n};\n\n" % "\n".join(rows)
    text += "inline constexpr std::size_t kDescriptorCount = %d;\n\n" % len(rows)
    text += "}  // namespace fixtures\n"
    with open(argv[2], "w", encoding="ascii", newline="\n") as fh:
        fh.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))

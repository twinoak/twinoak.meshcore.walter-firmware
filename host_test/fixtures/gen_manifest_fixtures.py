    bad_base_manifest("repeater-base-format-bin",
                      lambda m: provision_of(m).update({"format": "bin"}),
                      "a provision file whose format is bin: check 2")
    bad_base_manifest("repeater-base-hex-swd",
                      lambda m: next(f for f in m["images"][0]["files"]
                                     if f["use"] == "swd").update({"format": "hex"}),
                      "an swd file whose format is hex: check 2")
    bad_base_manifest("repeater-base-not-nrf52840",
                      lambda m: m["images"][0].update({"mcu": "esp32s3"}),
                      "a provision file on a board whose mcu is not nrf52840: check 2")


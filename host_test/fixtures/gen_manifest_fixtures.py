def c_string(value):
    if value is None:
        return "nullptr"
    out = []
    for ch in value:
        if ch in ('"', "\\"):
            out.append("\\" + ch)
        elif " " <= ch <= "~":
            out.append(ch)
        else:
            raise ValueError("fixture string %r is not printable ASCII" % value)
    return '"' + "".join(out) + '"'


def c_path(path):
    return c_string(os.path.abspath(path).replace("\\", "/"))


def read(fixtures, name):
    with open(os.path.join(fixtures, name), "rb") as fh:
        return fh.read()


def main(argv):
    if len(argv) != 4:
        print(__doc__)
        return 2
    fixtures, out_dir, out_h = argv[1], argv[2], argv[3]
    os.makedirs(out_dir, exist_ok=True)
    index = json.loads(read(fixtures, "index.json"))
    repeater = json.loads(read(fixtures, "manifest-repeater.json"))
    repeater_base = json.loads(read(fixtures, "manifest-repeater-base.json"))
    rep_bin = read(fixtures, "image-repeater.bin")
    two = read(fixtures, "image-two-descriptors.bin")
    broken = read(fixtures, "image-broken-descriptor.bin")

    def use_of(row):
        """The `use` of the entry index.json's `files` row names, out of that manifest."""
        manifest = json.loads(read(fixtures, row["manifest"]))
        for image in manifest["images"]:
            for entry in image["files"]:
                if entry["name"] == row["name"]:
                    return entry["use"]
        raise ValueError("%s names no file %r" % (row["manifest"], row["name"]))

    def write(name, data):
        with open(os.path.join(out_dir, name), "wb") as fh:
            fh.write(data)

    def signed(name, data, about, file=None, file_in_spec=False):
        """Writes <name>.json and its signature by the test key; returns the variant row."""
        write(name + ".json", data)
        write(name + ".json.sig", manifestref.sign(manifestref.TEST_PRIVATE, data).encode("ascii"))
        return (name, name + ".json", name + ".json.sig", file, file_in_spec, about)

    def with_swd_file(manifest, blob, name=None):
        """A copy of the manifest whose swd entry describes `blob`."""
        m = json.loads(json.dumps(manifest))
        for f in m["images"][0]["files"]:
            if f["use"] == "swd":
                f["size"] = len(blob)
                f["sha256"] = hashlib.sha256(blob).hexdigest()
                if name:
                    f["name"] = name
        return m

    variants = []

    # 1. The same manifest, reordered and re-indented: what is signed is the bytes, not a form.
    reordered = (json.dumps(repeater, indent=4, sort_keys=True, separators=(" , ", " : ")) + "\r\n").encode("utf-8")
    manifestref.validate(json.loads(reordered))
    variants.append(signed("repeater-reordered", reordered,
                           "the repeater manifest with sorted keys, four-space indent and CR LF: accepted",
                           "image-repeater.bin", True))

    # 2. Refused at check 2.
    m = json.loads(json.dumps(repeater))
    m["product"] = "twinoak-toaster-firmware"
    variants.append(signed("repeater-unknown-product", manifestref.canonical(m), "unknown product: check 2"))
    m = json.loads(json.dumps(repeater))
    m["schema"] = 2
    variants.append(signed("repeater-schema-2", manifestref.canonical(m), "schema 2: check 2"))

    # 3. Refused at check 3: the image requires what this build is not.
    m = json.loads(json.dumps(repeater))
    m["images"][0]["requires"]["link_major"] = 2
    variants.append(signed("repeater-requires-link-2", manifestref.canonical(m),
                           "requires.link_major 2: check 3", "image-repeater.bin", True))
    m = json.loads(json.dumps(repeater))
    m["link"]["major"] = 2
    m["images"][0]["requires"]["link_major"] = 2
    variants.append(signed("repeater-link-2", manifestref.canonical(m),
                           "the manifest's link.major 2: check 3", "image-repeater.bin", True))
    m = json.loads(json.dumps(repeater))
    m["images"][0]["requires"]["walter"] = "9.0.0"
    variants.append(signed("repeater-requires-walter-9", manifestref.canonical(m),
                           "requires.walter 9.0.0: check 3", "image-repeater.bin", True))
    m = json.loads(json.dumps(repeater))
    del m["images"][0]["requires"]
    variants.append(signed("repeater-no-requires", manifestref.canonical(m),
                           "no requires at all: accepted by any build", "image-repeater.bin", True))

    # 5. Refused at check 5: the entry's hash is a file whose descriptor is wrong.
    variants.append(signed("repeater-two-descriptors", manifestref.canonical(with_swd_file(repeater, two)),
                           "the swd file is image-two-descriptors.bin: check 5",
                           "image-two-descriptors.bin", True))
    variants.append(signed("repeater-broken-descriptor", manifestref.canonical(with_swd_file(repeater, broken)),
                           "the swd file is image-broken-descriptor.bin: check 5",
                           "image-broken-descriptor.bin", True))
    other_desc = manifestref.make_descriptor("repeater", "0.3.0+abc1234", "rak4630-dual-a", "868", 1, 0)
    other = manifestref.fake_image(other_desc, 4096, 0x400, 1)
    write("image-other-board.bin", other)
    variants.append(signed("repeater-other-board-descriptor", manifestref.canonical(with_swd_file(repeater, other)),
                           "the swd file's descriptor says board rak4630-dual-a: check 5",
                           "image-other-board.bin", False))
    other_version = manifestref.make_descriptor("repeater", "0.3.1+abc1234", "rak4630-single", "868", 1, 0)
    other_v = manifestref.fake_image(other_version, 4096, 0x400, 1)
    write("image-other-version.bin", other_v)
    variants.append(signed("repeater-other-version-descriptor", manifestref.canonical(with_swd_file(repeater, other_v)),
                           "the swd file's descriptor says version 0.3.1: check 5",
                           "image-other-version.bin", False))

    # 6. Refused at check 6: the region is outside the board profile (0x26000..0xED000), and the
    #    file fits it, so check 2 passes.
    m = json.loads(json.dumps(repeater))
    m["images"][0]["app_region"] = {"start": "0x00020000", "end": "0x000D4000"}
    for f in m["images"][0]["files"]:
        if f["use"] == "swd":
            f["load_address"] = "0x00020000"
    manifestref.validate(m)
    variants.append(signed("repeater-region-outside-profile", manifestref.canonical(m),
                           "app_region 0x20000..0xD4000, below the profile's start: check 6",
                           "image-repeater.bin", True))
    m = json.loads(json.dumps(repeater))
    m["images"][0]["app_region"] = {"start": "0x00026000", "end": "0x000F0000"}
    manifestref.validate(m)
    variants.append(signed("repeater-region-above-profile", manifestref.canonical(m),
                           "app_region 0x26000..0xF0000, past the profile's end (into the file system): check 6",
                           "image-repeater.bin", True))

    # Choosing: three images, the right one among them.
    m = json.loads(json.dumps(repeater))
    img868 = m["images"][0]
    img433 = json.loads(json.dumps(img868))
    img433["id"] = "repeater.rak4630-single.433"
    img433["band"] = "433"
    for f in img433["files"]:
        f["name"] = f["name"].replace("-868-", "-433-")
    scanner = json.loads(json.dumps(img868))
    scanner["id"] = "scanner.rak4630-single.868"
    scanner["role"] = "scanner"
    for f in scanner["files"]:
        f["name"] = f["name"].replace("repeater", "scanner")
    m["images"] = [img433, scanner, img868]
    manifestref.validate(m)
    variants.append(signed("repeater-three-images", manifestref.canonical(m),
                           "three images: 433, the scanner, then the 868 repeater (the fixture image): accepted",
                           "image-repeater.bin", True))

    # More images than the parser holds: refused at check 2 with its own reason.
    m = json.loads(json.dumps(repeater))
    images = []
    for i in range(MANY_IMAGES):
        img = json.loads(json.dumps(img868))
        img["id"] = "repeater.rak4630-single.%d" % (800 + i)
        img["band"] = "%d" % (800 + i)
        images.append(img)
    m["images"] = images
    manifestref.validate(m)
    variants.append(signed("repeater-many-images", manifestref.canonical(m),
                           "%d images, more than the parser holds: check 2" % MANY_IMAGES))

    # ---- the image store's images (task p2-02) -------------------------------------------------
    # A repeater (or scanner) image of a chosen size, with a descriptor that agrees with a
    # manifest of its own: the store's tests need images of several sizes - one inside a sector,
    # one of a few whole sectors, one that crosses two of the store's resume points - and every
    # one of them has to pass all six checks, because an AcceptedImage is the only key to the
    # store's door.
    store_images = []

    def store_image(name, size, about, role="repeater", version=None, band="868", seed=1):
        version = version or ("0.3.0+" + name.replace("-", "")[:7])
        desc = manifestref.make_descriptor(role, version, "rak4630-single", band, 1, 0)
        # The descriptor sits on a 4-byte boundary, past the vector table a real image starts
        # with; 0x400 is where the spec's own fixture images carry theirs.
        blob = manifestref.fake_image(desc, size, 0x400 if size > 0x400 + 96 else 0, seed)
        m = json.loads(json.dumps(repeater))
        m["version"] = version
        m["tag"] = "v" + version.split("+")[0]
        img = m["images"][0]
        img["role"] = role
        img["band"] = band
        img["id"] = "%s.rak4630-single.%s" % (role, band)
        for f in img["files"]:
            f["name"] = "twinoak-%s-rak4630-single-%s-%s.%s" % (role, band, name, f["format"])
            if f["use"] == "swd":
                f["size"] = len(blob)
                f["sha256"] = hashlib.sha256(blob).hexdigest()
        manifestref.validate(m)
        write(name + ".bin", blob)
        signed(name, manifestref.canonical(m), about, name + ".bin", False)
        store_images.append((name, name + ".json", name + ".json.sig", name + ".bin", len(blob),
                             role, version, band, about))

    store_image("store-a", 5 * 4096, "five whole sectors: the store's everyday image", seed=11)
    store_image("store-b", 5 * 4096, "the same size, other bytes: a second image over the first",
                version="0.3.1+bbbbbbb", seed=22)
    store_image("store-part", 1000, "under one sector: the tail of a write is a partial sector",
                seed=33)
    store_image("store-exact", 2 * 4096, "exactly two sectors: no tail at all", seed=44)
    store_image("store-resume", 150000,
                "150 000 bytes: two of the store's 64 KB resume points fall inside it", seed=55)
    store_image("store-scanner", 2 * 4096, "a scanner image, for the scanner slot", role="scanner",
                version="0.3.0+scanner", seed=66)
    # The radio's update (task p2-03) flashes these through the bit-level SWD simulator, many
    # times over in its power-loss loops, so they are one page each: a golden image and a newer
    # candidate, each with a version of its own for the health check to hold HELLO against.
    store_image("update-golden", 4096, "one page: the golden image of the update tests",
                version="0.3.0+golden0", seed=77)
    store_image("update-candidate", 4096, "one page: the candidate of the update tests",
                version="0.3.1+candid0", seed=88)

    # ---- the Walter's own images (task p2-04) ---------------------------------------------------
    # An `ota` file of this firmware's own product - role manager, board walter, band lte-m - with
    # a descriptor that agrees with a manifest of its own, derived from the spec's walter manifest.
    # The self-update's rules the tests hold these to: the file fits the other slot (the fake's
    # slots are 64 KB), its load_address is an application slot's offset (ota_0's, 0x10000, as the
    # release tooling writes it), and S-7's "speaks both majors": an image whose link.major is not
    # the radio's is let in only if requires.link_major names the radio's.
    walter = json.loads(read(fixtures, "manifest-walter.json"))

    def walter_image(name, size, about, version, link_major=1, requires_link_major=1,
                     load_address=0x10000, seed=1):
        desc = manifestref.make_descriptor("manager", version, "walter", "lte-m", link_major, 0)
        blob = manifestref.fake_image(desc, size, 0x400 if size > 0x400 + 96 else 0, seed)
        m = json.loads(json.dumps(walter))
        m["version"] = version
        m["tag"] = "v" + version.split("+")[0]
        m["link"]["major"] = link_major
        img = m["images"][0]
        if requires_link_major is None:
            img.pop("requires", None)
        else:
            img["requires"] = {"link_major": requires_link_major}
        for f in img["files"]:
            f["name"] = "twinoak-walter-%s.%s" % (name, f["format"])
            if f["use"] == "ota":
                f["size"] = len(blob)
                f["sha256"] = hashlib.sha256(blob).hexdigest()
                f["load_address"] = "0x%08X" % load_address
        manifestref.validate(m)
        write(name + ".bin", blob)
        signed(name, manifestref.canonical(m), about, name + ".bin", False)
        store_images.append((name, name + ".json", name + ".json.sig", name + ".bin", len(blob),
                             "manager", version, "lte-m", about))

    walter_image("self-a", 3 * 4096, "the Walter's own image: three pages, link 1", "0.4.0+w1", seed=101)
    walter_image("self-b", 2 * 4096 + 100, "another, an odd size, no requires", "0.4.1+w2",
                 requires_link_major=None, seed=102)
    walter_image("self-link2-both", 2 * 4096, "speaks link major 2 and says it tolerates 1: allowed (S-7)",
                 "0.5.0+w3", link_major=2, requires_link_major=1, seed=103)
    walter_image("self-link2-only", 2 * 4096, "speaks link major 2 and requires 2: refused at check 3",
                 "0.5.0+w4", link_major=2, requires_link_major=2, seed=104)
    walter_image("self-link2-silent", 2 * 4096, "speaks link major 2 and says nothing of 1: refused by the self-update",
                 "0.5.0+w5", link_major=2, requires_link_major=None, seed=105)
    walter_image("self-big", 70000, "larger than the fake's 64 KB slot: refused as too large", "0.4.2+w6",
                 seed=106)
    walter_image("self-other-slot", 3 * 4096, "load_address ota_1's: allowed (either slot's offset is)",
                 "0.4.3+w7", load_address=0x310000, seed=107)

    # ---- the base (task p5-01): FIRMWARE-MANIFEST.md §4a ---------------------------------------
    # A `provision` file that meets every rule, of a size the test asks for, and a manifest of its
    # own that names it - so that a store test and a verdict test can hold a real AcceptedBase,
    # which is the only key to the store's base door.
    import struct as _struct

    def words(*values):
        return b"".join(_struct.pack("<I", v) for v in values)

    def base_hex(sd_end=0x26000, nrffw0=0xF4000, extra=(), seed=7):
        filler = manifestref.fake_image(b"", 160, 0, seed)
        chunks = [
            (0x00000000, filler),                                  # the MBR
            (0x00001000, filler),                                  # the SoftDevice ...
            (0x00003000, words(0, manifestref.SD_MAGIC_VALUE, sd_end, 0x00B6,
                               manifestref.SD_S140_ID, manifestref.SD_S140_VERSION)),
            (nrffw0, manifestref.fake_image(b"", 160, 0, seed + 1)),  # the bootloader
            (0x10001014, words(nrffw0, 0x000FE000)),               # NRFFW[0], NRFFW[1]
        ]
        return manifestref.ihex(chunks + list(extra))

    store_bases = []

    def store_base(name, data, about, region=FIXTURE_REGION, bootloader=0xF4000,
                   valid_for_the_board=True, mangle=None):
        """<name>.hex, a manifest of its own naming it, and the signature."""
        m = json.loads(json.dumps(repeater_base))
        img = m["images"][0]
        img["app_region"] = {"start": "0x%08X" % region[0], "end": "0x%08X" % region[1]}
        for f in img["files"]:
            if f["use"] == "swd":
                f["load_address"] = "0x%08X" % region[0]
            if f["use"] == "provision":
                f["name"] = name + ".hex"
                f["size"] = len(data)
                f["sha256"] = hashlib.sha256(data).hexdigest()
        if mangle is not None:
            mangle(m)
        else:
            manifestref.validate(m)
        write(name + ".hex", data)
        signed(name, manifestref.canonical(m), about, name + ".hex", False)
        flash_bytes = manifestref.validate_provision(data, region[0], region[1])["flash_bytes"] \
            if valid_for_the_board or True else 0
        store_bases.append((name, name + ".json", name + ".json.sig", name + ".hex", len(data),
                            bootloader, flash_bytes, region[0], region[1], valid_for_the_board,
                            about))

    # The everyday one: the specification's own stand-in base, under a manifest of this directory
    # so that the store's tests do not depend on the spec's example region.
    store_base("base-small", base_hex(),
               "the shape of the specification's stand-in base, 688 bytes of text: the store's "
               "everyday base")
    # One that crosses two of the store's 64 KB resume points: 48 KB of SoftDevice below the
    # application region is ~132 KB of Intel HEX.
    big = base_hex(extra=[(0x00004000, manifestref.fake_image(b"", 48 * 1024, 0, 21))], seed=31)
    store_base("base-resume", big,
               "48 KB of flash bytes, ~132 KB of text: two of the store's 64 KB resume points "
               "fall inside it")
    # Larger than a base area of the store holds (640 KB of text), so that the door's refusal -
    # before anything is erased - is a real refusal of a real file. Intel HEX of one data byte a
    # record costs 13 characters a byte, so 52 KB of flash bytes below the application region is
    # ~690 KB of text: a silly way to write a base, and a valid one.
    def one_byte_records(address, blob):
        lines = []
        upper = None
        for i, byte in enumerate(blob):
            at = address + i
            if at >> 16 != upper:
                upper = at >> 16
                raw = bytes([2, 0, 0, 4, upper >> 8, upper & 0xFF])
                lines.append(":" + (raw + bytes([(-sum(raw)) & 0xFF])).hex().upper())
            raw = bytes([1, (at >> 8) & 0xFF, at & 0xFF, 0, byte])
            lines.append(":" + (raw + bytes([(-sum(raw)) & 0xFF])).hex().upper())
        return "\n".join(lines) + "\n"

    end_record = ":00000001FF\n"
    filler = manifestref.fake_image(b"", 52 * 1024, 0, 51)
    sparse = (base_hex().decode("ascii").replace(end_record, "")
              + one_byte_records(0x00004000, filler) + end_record)
    store_base("base-too-large", sparse.encode("ascii"),
               "~690 KB of text, one data byte a record: larger than the 640 KB a base area holds")
    # A base that is one against the fixture manifest's region and not against the board's: its
    # bootloader sits at the fixture region's end, 0xD4000, which is inside the board's
    # application region (0x26000..0xED000). Check 5p judges a base against **the board's**, so
    # this one is refused - and the test that shows it is the one that shows which region wins.
    in_the_region = manifestref.ihex([
        (0x00000000, manifestref.fake_image(b"", 160, 0, 41)),
        (0x00001000, manifestref.fake_image(b"", 160, 0, 42)),
        (0x00003000, words(0, manifestref.SD_MAGIC_VALUE, 0x26000, 0x00B6,
                           manifestref.SD_S140_ID, manifestref.SD_S140_VERSION)),
        (0x000D4000, manifestref.fake_image(b"", 160, 0, 43)),
        (0x10001014, words(0x000D4000, 0x000FE000)),
    ])
    store_base("base-in-the-manifest-region", in_the_region,
               "a base against the manifest's region (bootloader at its end, 0xD4000) and not "
               "against the board's: check 5p refuses it",
               bootloader=0xD4000, valid_for_the_board=False)

    # Every base fixture of the specification under a manifest of its own, so that a verdict test
    # can reach each one the way a unit does - through checks 1 to 4 and then 5p - and see §4a's
    # sentence come out of the whole chain and not out of the reader alone.

#!/usr/bin/env python3
"""The firmware's trust table, generated from keys/release-keys.txt at build time (task p2-01).

    python tools/gen_trust_table.py keys/release-keys.txt <out>/trust_keys.h
    python tools/gen_trust_table.py keys/release-keys.txt <out>/trust_keys.h --test-key spec/fixtures/manifest/index.json

Writes a C++ header with the public keys a build of this firmware trusts a release manifest to
be signed with (spec/FIRMWARE-MANIFEST.md §3: room for three), each with its key id. Both CMake
projects run it (components/core/CMakeLists.txt, host_test/CMakeLists.txt) and
components/core/image/trust.cpp includes what it writes.

The table is read by tools/release/verify_release.py's loader - the same rules as the release
gate: `ed25519 <key id> <public hex>` a line, the id recomputed and held, at most three, and
never the specification's test key. --test-key appends that key, read from the fixture index
rather than written down here, and marks the table: that is the +TESTKEY build, which the release
tooling refuses and main warns about at every boot.

Standard library only (manifestref.key_id is SHA-256 from hashlib). Deterministic: the same
inputs give the same bytes.
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(REPO, "spec", "tools"))
sys.path.insert(0, os.path.join(HERE, "release"))

import manifestref  # noqa: E402  spec/tools/manifestref.py
import verify_release  # noqa: E402  tools/release/verify_release.py: load_keys, Refused

MAX_KEYS = 3


def test_key(index_path):
    """The public half of the specification's test key, from the fixture index, its id checked."""
    with open(index_path, encoding="utf-8") as fh:
        index = json.load(fh)
    public = bytes.fromhex(index["test_public_key"])
    if len(public) != 32:
        raise verify_release.Refused("%s: test_public_key is not 32 bytes" % index_path)
    if manifestref.key_id(public) != index["test_key_id"]:
        raise verify_release.Refused("%s: test_public_key and test_key_id do not agree" % index_path)
    return public


def c_bytes(data):
    return ", ".join("0x%02x" % b for b in data)


def render(keys, trusts_test_key, source):
    """The header's text for a list of raw public keys."""
    if len(keys) > MAX_KEYS:
        raise verify_release.Refused("%d keys; a build has room for %d (section 3)" % (len(keys), MAX_KEYS))
    lines = [
        "// Generated by tools/gen_trust_table.py from %s. Do not edit; it is rewritten by every build." % source,
        "//",
        "// The public keys this build trusts a release manifest to be signed with, each with its key id",
        "// (spec/FIRMWARE-MANIFEST.md section 3). Unused rows are zero; kTrustedKeyCount says how many",
        "// are real. kTrustsTestKey is true only in a build made with -DTWINOAK_TRUST_TEST_KEY=1.",
        "#pragma once",
        "",
        "#include <cstddef>",
        "",
        '#include "core/image/trust.h"',
        "",
        "namespace core {",
        "namespace image {",
        "namespace generated {",
        "",
        "inline constexpr std::size_t kTrustedKeyCount = %d;" % len(keys),
        "inline constexpr bool kTrustsTestKey = %s;" % ("true" if trusts_test_key else "false"),
        "",
        "inline constexpr TrustedKey kTrustedKeys[kMaxTrustedKeys] = {",
    ]
    for i in range(MAX_KEYS):
        if i < len(keys):
            key = keys[i]
            key_id = bytes.fromhex(manifestref.key_id(key))
            lines.append("    // key id %s" % manifestref.key_id(key))
            lines.append("    {{%s}," % c_bytes(key_id))
            lines.append("     {%s}}," % c_bytes(key))
        else:
            lines.append("    {{0, 0, 0, 0, 0, 0, 0, 0}, {0}},  // unused")
    lines += [
        "};",
        "",
        "}  // namespace generated",
        "}  // namespace image",
        "}  // namespace core",
    ]
    return "\n".join(lines) + "\n"


def generate(keys_path, index_path):
    keys = verify_release.load_keys(keys_path)
    source = os.path.relpath(keys_path, REPO).replace("\\", "/")
    if index_path:
        keys.append(test_key(index_path))
        source += " + the test key of " + os.path.relpath(index_path, REPO).replace("\\", "/")
    return render(keys, bool(index_path), source)


def main(argv):
    args = list(argv[1:])
    index_path = None
    if "--test-key" in args:
        at = args.index("--test-key")
        if at + 1 >= len(args):
            print("--test-key needs the path of spec/fixtures/manifest/index.json", file=sys.stderr)
            return 2
        index_path = args[at + 1]
        del args[at:at + 2]
    if len(args) != 2:
        print(__doc__)
        return 2
    keys_path, out_path = args
    try:
        text = generate(keys_path, index_path)
    except verify_release.Refused as exc:
        print("REFUSED: %s" % exc, file=sys.stderr)
        return 1
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    # Written only when it changed, so that an unchanged table does not rebuild what includes it.
    if os.path.isfile(out_path):
        with open(out_path, "r", encoding="ascii", newline="") as fh:
            if fh.read() == text:
                return 0
    with open(out_path, "w", encoding="ascii", newline="\n") as fh:
        fh.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
